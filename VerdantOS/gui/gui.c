void gui_draw_char(int x, int y, int c, uint32_t color) {
    if (c < 0 || c >= 128) return;
    const unsigned char* glyph = font8x8[(unsigned char)c];
    for (int row = 0; row < 8; row++) {
        unsigned char line = glyph[row];
        for (int col = 0; col < 8; col++) {
            if (line & (1 << (7 - col))) {
                gui_draw_pixel(x + col, y + row, color);
            }
        }
    }
}

void gui_draw_string(int x, int y, const char* str, uint32_t color) {
    int i = 0;
    while (str[i] != '\0') {
        gui_draw_char(x + (i * 8), y, str[i], color);
        i++;
    }
}

void gui_start(void) {
    gui_init();
    init_processes();

    create_process("terminal", 100, 60, 440, 280);
    create_process("taskmgr", 240, 130, 380, 240);

    uint32_t bg_color = 0x001E1E2E; 

    int old_mx = -1;
    int old_my = -1;

    uint32_t cursor_backup[16][12];
    int has_backup = 0;

    gui_draw_rect(0, 0, SCREEN_WIDTH, SCREEN_HEIGHT, bg_color);
    draw_all_processes();

    while (1) {
        poll_mouse();

        int mx = get_mouse_x();
        int my = get_mouse_y();
        uint8_t mb = get_mouse_buttons();

        int processes_changed = update_processes(mx, my, mb, SCREEN_WIDTH, SCREEN_HEIGHT);

        if (processes_changed) {
            has_backup = 0;
            gui_draw_rect(0, 0, SCREEN_WIDTH, SCREEN_HEIGHT, bg_color);
            draw_all_processes();
        }

        if (mx != old_mx || my != old_my) {
            if (has_backup && old_mx >= 0 && old_my >= 0) {
                for (int cy = 0; cy < 16; cy++) {
                    for (int cx = 0; cx < 12; cx++) {
                        int px = old_mx + cx;
                        int py = old_my + cy;
                        if (px >= 0 && px < SCREEN_WIDTH && py >= 0 && py < SCREEN_HEIGHT) {
                            framebuffer[py * SCREEN_WIDTH + px] = cursor_backup[cy][cx];
                        }
                    }
                }
            }

            for (int cy = 0; cy < 16; cy++) {
                for (int cx = 0; cx < 12; cx++) {
                    int px = mx + cx;
                    int py = my + cy;
                    if (px >= 0 && px < SCREEN_WIDTH && py >= 0 && py < SCREEN_HEIGHT) {
                        cursor_backup[cy][cx] = framebuffer[py * SCREEN_WIDTH + px];
                    } else {
                        cursor_backup[cy][cx] = bg_color;
                    }
                }
            }
            has_backup = 1;

            gui_draw_cursor(mx, my);

            old_mx = mx;
            old_my = my;
        }
    }
}